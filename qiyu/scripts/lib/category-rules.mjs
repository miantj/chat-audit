export function thirdCategory(value) {
  return [...new Set(String(value || '').split(',').map((path) => {
    const parts = path.split('/').map((part) => part.trim()).filter(Boolean);
    return parts.length === 1 ? parts[0] : parts[2] || '';
  }).filter(Boolean))].join(',');
}

