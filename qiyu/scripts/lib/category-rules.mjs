export const CATEGORY_RULES = RAW_RULES;

const FALLBACK_RULES = new Set([
  '关于售前其他咨询',
  '其他反馈',
  '童装其他反馈'
]);

const CHILD_RULES = new Set(CATEGORY_RULES.map((rule) => rule.name).filter((name) => name.startsWith('童装')));

// 统一常见说法，减少“售价/价格、两个/2、没同步/不同步”等写法造成的漏判。
const ALIASES = [
  [/售价/g, '价格'],
  [/价位/g, '价格'],
  [/两个/g, '2个'],
  [/两款/g, '2款'],
  [/没有|没/g, ''],
  [/请问|为什么|为啥/g, '']
];

function normalize(value) {
  let text = String(value || '').toLowerCase().replace(/[\s，。！？、；：:,.!?]/g, '');
  for (const [pattern, replacement] of ALIASES) text = text.replace(pattern, replacement);
  return text;
}

function scoreRule(rule, text) {
  const hits = rule.keywords.filter((keyword) => {
    const key = normalize(keyword);
    return key.length >= 2 && text.includes(key);
  });
  const score = hits.reduce((total, keyword) => {
    const length = normalize(keyword).length;
    return total + (length >= 4 ? 2 + Math.min(length, 12) / 8 : 1);
  }, 0);
  return { name: rule.name, score, hits };
}

export function scoreCategories(text) {
  const normalized = normalize(text);
  return CATEGORY_RULES
    .map((rule) => scoreRule(rule, normalized))
    .sort((a, b) => b.score - a.score);
}

function applyPrecedence(scores, text) {
  const t = normalize(text);
  const has = (pattern) => pattern.test(t);
  let result = scores;

  // 童装词是领域限定；没有童装/儿童语境时，不能被“优惠/价格”等通用词带入。
  if (!has(/童装|儿童|宝宝|小孩|婴儿/)) result = result.filter((x) => !CHILD_RULES.has(x.name));
  else {
    if (result.some((x) => CHILD_RULES.has(x.name) && x.name !== '童装频道咨询')) {
      result = result.filter((x) => x.name !== '童装频道咨询');
    }
    // 已有具体童装叶子时，不要再叠通用活动/收费标签。
    if (result.some((x) => CHILD_RULES.has(x.name))) {
      result = result.filter((x) => !['平台活动咨询', '收费标准'].includes(x.name));
    }
  }

  // 场景词优先于平台通用活动词。
  if (has(/直播/)) {
    result = result.filter((x) => !['平台活动咨询', '新人活动咨询'].includes(x.name));
    if (has(/活动|优惠|券|福利|价格/)) {
      result = result.filter((x) => !['功能指引', '功能使用咨询'].includes(x.name));
    }
  }
  if (has(/新人|新客|首单/)) result = result.filter((x) => x.name !== '平台活动咨询');
  if (has(/无忧退/)) result = result.filter((x) => x.name !== '平台活动咨询');
  if (has(/月卡|运费卡|包月运费|运费包月|运费抵扣/)) {
    result = result.filter((x) => x.name !== '运费收取规则');
  } else if (has(/包邮|免运费/)) {
    // 「包邮」 alone 是运费制度问询，不是月卡产品。
    result = result.filter((x) => x.name !== '运费月卡咨询');
    if (!result.some((x) => x.name === '运费收取规则')) {
      result = [{ name: '运费收取规则', score: 2, hits: ['包邮'] }, ...result];
    }
  }

  // 纯询价/多少钱：走价格咨询，不要落到铺货「收费标准」。
  if (has(/多少钱|贵|便宜|价格|优惠|折扣|降价/) && !has(/收费|年费|会员费|服务费|开通费/)) {
    result = result.filter((x) => x.name !== '收费标准');
  }

  // 推荐商家 vs 商务合作意向。
  if (has(/推荐商家|档口推荐|供应商|优质商家|靠谱商家|推荐个商家/)) {
    result = result.filter((x) => x.name !== '合作意向');
  } else if (has(/合作|代理/) && !has(/推荐/)) {
    result = result.filter((x) => x.name !== '推荐合作');
  }

  if (has(/批量|拿得多|走量|谈价/)) {
    result = result.filter((x) => !['一手模式咨询', '童装拿货规则'].includes(x.name));
  }
  if (has(/铺货/) && has(/失败|报错|上架|发布/)) {
    if (!result.some((x) => x.name === '铺货失败')) {
      result = [{ name: '铺货失败', score: 3, hits: ['铺货失败'] }, ...result];
    }
    result = result.filter((x) => ['铺货失败', '产品bug'].includes(x.name));
  }
  if (has(/铺货/) && has(/怎么用|功能|操作|设置/)) {
    result = result.filter((x) => !['一键铺货咨询', '功能指引'].includes(x.name));
  }
  if (has(/物流/) && has(/同步|单号|轨迹/)) {
    if (!result.some((x) => x.name === '物流信息同步')) {
      result = [{ name: '物流信息同步', score: 3, hits: ['物流信息同步'] }, ...result];
    }
    result = result.filter((x) => !['功能使用咨询', '订单同步咨询'].includes(x.name));
  }
  if (has(/功能/) && !has(/铺货|订单|同步/)) {
    result = result.filter((x) => x.name !== '功能使用咨询');
  }

  // 价格子类优先于款式/兜底价格类。
  if (has(/同款.*(2个|价|价格)|两个.*(售价|价格)/)) {
    result = result.filter((x) => !['款式咨询', '其他反馈'].includes(x.name));
  }
  if (has(/加价规则/) && !has(/商品加价|商品定价/)) {
    result = result.filter((x) => x.name !== '商品加价规则');
  }
  if (has(/涨价|上涨|上调/)) {
    if (!result.some((x) => x.name === '反馈涨价')) {
      result = [{ name: '反馈涨价', score: 3, hits: ['涨价'] }, ...result];
    }
    result = result.filter((x) => !['其他反馈', '价格异常'].includes(x.name));
  }
  if (has(/别家|别的|其他家|淘宝|档口|渠道|外面/) && has(/贵|便宜/)) {
    if (!result.some((x) => x.name === '比其他渠道贵')) {
      result = [{ name: '比其他渠道贵', score: 3, hits: ['渠道比价'] }, ...result];
    }
    result = result.filter((x) => !['投诉加价太高', '其他反馈'].includes(x.name));
  }
  if (has(/批量|拿得多|走量|谈价/)) result = result.filter((x) => !['其他反馈'].includes(x.name));
  if (has(/涨价|上调/)) result = result.filter((x) => !['其他反馈'].includes(x.name));

  if (result.some((x) => !FALLBACK_RULES.has(x.name))) {
    result = result.filter((x) => !FALLBACK_RULES.has(x.name));
  }

  const top = result[0]?.score || 0;
  return result.filter((x) => x.score >= Math.max(1, top * 0.42));
}

/**
 * 优先使用文档规则；多意图以逗号分隔，供飞书多选字段拆分。
 * @returns { category: string, source: 'doc'|'qiyu' }
 */
export function resolveCategory(userQuestion, qiyuCategory) {
  if (!String(userQuestion || '').trim()) return { category: thirdCategory(qiyuCategory), source: 'qiyu' };
  const hits = applyPrecedence(scoreCategories(userQuestion).filter((item) => item.score > 0), userQuestion);
  if (!hits.length) return { category: thirdCategory(qiyuCategory), source: 'qiyu' };
  return {
    category: [...new Set(hits.map((item) => aiDisplayCategory(item.name)))].join(','),
    source: 'doc'
  };
}
